#!/usr/bin/env node
/**
 * Sync Crew Hub UI artifacts from the canonical engine manifest.
 *
 * The catalog itself is the Crew Enhancement snapshot
 * (`packages/engine/data/crew-catalog.manifest.json`). This script never
 * synthesizes new crews. Running `generate-crew-hub.mjs` without
 * `--force-synthesize` delegates here.
 */
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  unlinkSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const HUB_DIR = join(__dirname, '../src/data/crew-hub');
const CATEGORIES_DIR = join(HUB_DIR, 'categories');
const PUBLIC_HUB_DIR = join(__dirname, '../public/crew-hub');
const INDEX_PATH = join(HUB_DIR, 'prebuilt-crews-index.ts');
const SEARCH_INDEX_PATH = join(HUB_DIR, 'search-index.ts');
const SEARCH_INDEX_PUBLIC_PATH = join(PUBLIC_HUB_DIR, 'search-index.json');
const MANIFEST_PATH = join(__dirname, '../../engine/data/crew-catalog.manifest.json');
const LEGACY_PATH = join(HUB_DIR, 'prebuilt-crews.ts');
const SHARED_MEDICAL_PATH = join(__dirname, '../../shared/src/constants/medical-hub.generated.ts');
const CATALOG_INDEX_PATH = join(__dirname, '../../engine/data/crew-hub-catalog-index.md');

function toPrebuiltCrew(crew) {
  const entry = {
    name: crew.name,
    title: crew.title,
    callsign: crew.callsign,
    description: crew.description,
    systemPrompt: crew.systemPrompt,
    tone: crew.tone ?? 'professional',
    expertise: crew.expertise ?? [],
    traits: crew.traits ?? [],
  };
  if (crew.tools) entry.tools = crew.tools;
  if (crew.tags) entry.tags = crew.tags;
  if (crew.honorsDoctorate) entry.honorsDoctorate = true;
  return entry;
}

export function syncCrewHubFromManifest() {
  if (!existsSync(MANIFEST_PATH)) {
    throw new Error(`Canonical crew catalog missing: ${MANIFEST_PATH}`);
  }

  const manifest = JSON.parse(readFileSync(MANIFEST_PATH, 'utf8'));
  const categories = Array.isArray(manifest.categories) ? manifest.categories : [];
  const crews = Array.isArray(manifest.crews) ? manifest.crews : [];

  if (categories.length === 0 || crews.length === 0) {
    throw new Error('Canonical crew catalog has no categories or crews');
  }

  const crewsByCategory = new Map();
  for (const category of categories) {
    crewsByCategory.set(category.id, []);
  }
  for (const crew of crews) {
    const bucket = crewsByCategory.get(crew.categoryId);
    if (!bucket) {
      throw new Error(`Crew ${crew.id} references unknown category ${crew.categoryId}`);
    }
    bucket.push(crew);
  }

  const categoryIconIds = Array.from(
    new Set(categories.map((category) => category.iconId).filter(Boolean)),
  );
  if (categoryIconIds.length === 0) {
    throw new Error('Canonical crew catalog categories are missing iconId values');
  }

  const indexContents = `/**
 * AUTO-GENERATED — run: node scripts/generate-crew-hub.mjs
 * Do not edit this file manually.
 *
 * Source of truth: packages/engine/data/crew-catalog.manifest.json
 * (Crew Enhancement catalog). This file is synced from that snapshot.
 */

export type PrebuiltCrewData = {
  name: string;
  title: string;
  callsign: string;
  description: string;
  systemPrompt: string;
  tone: string;
  expertise: string[];
  traits: string[];
  tools?: string[];
  tags?: string[];
  honorsDoctorate?: boolean;
};

export type CategoryIconId = ${categoryIconIds.map((id) => `'${id}'`).join(' | ')};

export type PrebuiltCategoryIndexEntry = {
  id: string;
  label: string;
  iconId: CategoryIconId;
};

export const PREBUILT_CATEGORY_INDEX: PrebuiltCategoryIndexEntry[] = ${JSON.stringify(
    categories.map(({ id, label, iconId }) => ({ id, label, iconId })),
    null,
    2,
  )};
`;

  mkdirSync(CATEGORIES_DIR, { recursive: true });
  writeFileSync(INDEX_PATH, indexContents, 'utf8');

  const searchIndex = [];
  for (const category of categories) {
    for (const crew of crewsByCategory.get(category.id) ?? []) {
      searchIndex.push({
        categoryId: category.id,
        categoryLabel: category.label,
        callsign: crew.callsign,
        name: crew.name,
        title: crew.title,
        expertise: (crew.expertise ?? []).slice(0, 2),
        searchText: crew.searchText || `${crew.name} ${crew.title} ${crew.callsign} ${crew.description}`.toLowerCase(),
      });
    }
  }

  mkdirSync(PUBLIC_HUB_DIR, { recursive: true });
  writeFileSync(SEARCH_INDEX_PUBLIC_PATH, JSON.stringify(searchIndex), 'utf8');
  writeFileSync(
    SEARCH_INDEX_PATH,
    `/**
 * AUTO-GENERATED — run: node scripts/generate-crew-hub.mjs
 * Do not edit this file manually.
 */

export type CrewSearchIndexEntry = {
  categoryId: string;
  categoryLabel: string;
  callsign: string;
  name: string;
  title: string;
  expertise: string[];
  searchText: string;
};
`,
    'utf8',
  );

  const medicalCategoryIds = categories
    .filter((category) => category.requiresMedicalDisclaimer)
    .map((category) => category.id);
  const medicalCatalogIds = crews
    .filter((crew) => crew.requiresMedicalDisclaimer)
    .map((crew) => crew.id);
  writeFileSync(
    SHARED_MEDICAL_PATH,
    `/** AUTO-GENERATED — run: node scripts/generate-crew-hub.mjs
 * Source of truth: packages/engine/data/crew-catalog.manifest.json
 */
export const MEDICAL_HUB_CATEGORY_IDS_GENERATED: readonly string[] = ${JSON.stringify(medicalCategoryIds, null, 2)};
export const MEDICAL_HUB_CATALOG_IDS_GENERATED: readonly string[] = ${JSON.stringify(medicalCatalogIds, null, 2)};
`,
    'utf8',
  );

  const indexLines = [
    `# Crew Hub Catalog Index`,
    ``,
    `Revision: **${manifest.revision}**`,
    `Categories: **${categories.length}**`,
    `Crew members: **${crews.length}**`,
    ``,
    `> Canonical catalog is the Crew Enhancement snapshot. Existing installs pick up this revision automatically (background catalog seed).`,
    ``,
  ];
  for (const category of categories) {
    const categoryCrews = crewsByCategory.get(category.id) ?? [];
    indexLines.push(`## ${category.label} (\`${category.id}\`) — ${categoryCrews.length} roles`);
    if (category.requiresMedicalDisclaimer) indexLines.push(`*Medical informational disclaimer required*`);
    for (const crew of categoryCrews) {
      indexLines.push(`- ${crew.title} — ${crew.name}`);
    }
    indexLines.push('');
  }
  writeFileSync(CATALOG_INDEX_PATH, indexLines.join('\n'), 'utf8');

  const keep = new Set(categories.map((category) => `${category.id}.ts`));
  for (const file of readdirSync(CATEGORIES_DIR)) {
    if (!file.endsWith('.ts')) continue;
    if (!keep.has(file)) unlinkSync(join(CATEGORIES_DIR, file));
  }

  for (const category of categories) {
    const categoryPath = join(CATEGORIES_DIR, `${category.id}.ts`);
    const prebuilt = (crewsByCategory.get(category.id) ?? []).map(toPrebuiltCrew);
    writeFileSync(
      categoryPath,
      `/**
 * AUTO-GENERATED — run: node scripts/generate-crew-hub.mjs
 * Do not edit this file manually.
 */
import type { PrebuiltCrewData } from '../prebuilt-crews-index';

export const PREBUILT_CREWS: PrebuiltCrewData[] = ${JSON.stringify(prebuilt, null, 2)};
`,
      'utf8',
    );
  }

  if (existsSync(LEGACY_PATH)) unlinkSync(LEGACY_PATH);

  console.log(
    `Synced Crew Hub artifacts from canonical manifest r${manifest.revision}: ${categories.length} categories, ${crews.length} crews`,
  );
}

const isDirectRun = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isDirectRun) {
  try {
    syncCrewHubFromManifest();
  } catch (err) {
    console.error(err instanceof Error ? err.message : err);
    process.exit(1);
  }
}
